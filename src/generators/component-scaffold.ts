/**
 * Component File & Export Barrel Emitter
 *
 * Writes decompiled React components and extracted SVG icons
 * to disk as clean TypeScript files, then generates the
 * main index.ts barrel export.
 */

import path from "node:path";
import fs from "node:fs/promises";
import type { DecompiledComponent, ExtractedIcon } from "../types/index.js";
import { createLogger } from "../core/logger.js";

const logger = createLogger("scaffold");

/**
 * Write all extracted components and icons to the output directory
 * and generate the barrel export index.ts.
 *
 * @param components - Decompiled components to write.
 * @param icons - Extracted icons to write.
 * @param outputDir - Target output directory (root of generated kit).
 */
export async function emitComponents(
  components: DecompiledComponent[],
  icons: ExtractedIcon[],
  outputDir: string
): Promise<void> {
  logger.info(
    `Emitting ${components.length} components and ${icons.length} icons...`
  );

  // Write component files
  for (const component of components) {
    const componentDir = path.join(outputDir, "src", "components", component.name);
    await fs.mkdir(componentDir, { recursive: true });

    await fs.writeFile(
      path.join(componentDir, `${component.name}.tsx`),
      component.componentCode
    );

    if (component.storyCode) {
      await fs.writeFile(
        path.join(componentDir, `${component.name}.stories.tsx`),
        component.storyCode
      );
    }
  }

  // Write icon files
  const iconsDir = path.join(outputDir, "src", "icons");
  await fs.mkdir(iconsDir, { recursive: true });

  for (const icon of icons) {
    const iconCode = generateIconComponent(icon);
    await fs.writeFile(path.join(iconsDir, `${icon.name}.tsx`), iconCode);
  }

  // Write icons barrel export
  const iconBarrel = icons
    .map((icon) => `export { ${icon.name} } from "./${icon.name}.js";`)
    .join("\n");
  await fs.writeFile(path.join(iconsDir, "index.ts"), iconBarrel + "\n");

  // Write main barrel export
  await writeBarrelExport(components, icons, outputDir);

  logger.info("Component and icon emission complete");
}

/**
 * Generate a React icon component from an ExtractedIcon.
 */
function generateIconComponent(icon: ExtractedIcon): string {
  const paths = icon.paths
    .map((p) => {
      const attrs = [`d="${p.d}"`];
      if (p.fillRule) attrs.push(`fillRule="${p.fillRule}"`);
      if (p.clipRule) attrs.push(`clipRule="${p.clipRule}"`);
      return `      <path ${attrs.join(" ")} />`;
    })
    .join("\n");

  return `import type { SVGProps } from "react";

export const ${icon.name} = (props: SVGProps<SVGSVGElement>) => (
  <svg
    xmlns="http://www.w3.org/2000/svg"
    viewBox="${icon.viewBox}"
    fill="none"
    stroke="currentColor"
    strokeWidth="2"
    strokeLinecap="round"
    strokeLinejoin="round"
    {...props}
  >
${paths}
  </svg>
);
`;
}

/**
 * Generate the main src/index.ts barrel export.
 */
async function writeBarrelExport(
  components: DecompiledComponent[],
  icons: ExtractedIcon[],
  outputDir: string
): Promise<void> {
  const lines: string[] = [
    '// Auto-generated by rea-steal-ui — Main Export Barrel',
    '',
    '// Components',
  ];

  for (const comp of components) {
    lines.push(`export { ${comp.name} } from "./components/${comp.name}/${comp.name}.js";`);
  }

  lines.push('', '// Icons');
  for (const icon of icons) {
    lines.push(`export { ${icon.name} } from "./icons/${icon.name}.js";`);
  }

  lines.push('');

  await fs.writeFile(path.join(outputDir, "src", "index.ts"), lines.join("\n"));
}

