/**
 * Tailwind Theme Generator
 *
 * Emits either a Tailwind CSS v4 (@theme directive in CSS) or
 * Tailwind CSS v3 (tailwind.config.ts) theme configuration from
 * extracted design tokens.
 */

import type { DesignTokens } from "../types/index.js";
import { createLogger } from "../core/logger.js";

const logger = createLogger("tailwind");

/**
 * Generate Tailwind theme configuration from extracted design tokens.
 *
 * @param tokens - Extracted design tokens.
 * @param version - Target Tailwind version ("3" or "4").
 * @returns Object containing the config file content and globals.css content.
 */
export async function generateTailwindConfig(
  tokens: DesignTokens,
  version: "3" | "4"
): Promise<{ configContent: string; globalsCss: string }> {
  logger.info(`Generating Tailwind ${version === "4" ? "v4 @theme" : "v3 config"}...`);

  const globalsCss = generateGlobalsCss(tokens);

  const configContent =
    version === "4"
      ? generateTailwindV4Theme(tokens)
      : generateTailwindV3Config(tokens);

  return { configContent, globalsCss };
}

/**
 * Generate globals.css with CSS custom properties for light and dark modes.
 */
function generateGlobalsCss(tokens: DesignTokens): string {
  const { colors } = tokens;

  return `/* Auto-generated by rea-steal-ui — Design Token CSS Variables */

:root {
  /* Background */
  --color-bg-canvas: ${colors.background.canvas};
  --color-bg-surface: ${colors.background.surface};
  --color-bg-elevated: ${colors.background.elevated};
  --color-bg-overlay: ${colors.background.overlay};

  /* Foreground */
  --color-fg-primary: ${colors.foreground.primary};
  --color-fg-secondary: ${colors.foreground.secondary};
  --color-fg-muted: ${colors.foreground.muted};
  --color-fg-inverse: ${colors.foreground.inverse};

  /* Border */
  --color-border-subtle: ${colors.border.subtle};
  --color-border-strong: ${colors.border.strong};
  --color-border-interactive: ${colors.border.interactive};

  /* Accent */
  --color-accent-primary: ${colors.accent.primary};
  --color-accent-hover: ${colors.accent.hover};
  --color-accent-focus: ${colors.accent.focus};

  /* Typography */
  --font-sans: ${tokens.typography.fontFamilies.sans ? tokens.typography.fontFamilies.sans.join(", ") : "sans-serif"};
  --font-mono: ${tokens.typography.fontFamilies.mono ? tokens.typography.fontFamilies.mono.join(", ") : "monospace"};
${Object.entries(tokens.typography.fontSizes)
  .map(([key, val]) => `  --font-size-${key}: ${val.fontSize};`)
  .join("\n")}
${Object.entries(tokens.typography.fontWeights || {})
  .map(([key, val]) => `  --font-weight-${key}: ${val};`)
  .join("\n")}

  /* Radii */
${Object.entries(tokens.radii)
  .map(([key, val]) => `  --radius-${key}: ${val};`)
  .join("\n")}

  /* Shadows */
${Object.entries(tokens.shadows)
  .map(([key, val]) => `  --shadow-${key}: ${val};`)
  .join("\n")}
}
`;
}

/**
 * Generate Tailwind CSS v4 @theme configuration.
 */
function generateTailwindV4Theme(_tokens: DesignTokens): string {
  return `/* Auto-generated by rea-steal-ui — Tailwind CSS v4 Theme */

@import "tailwindcss";

@theme {
  --font-sans: var(--font-sans);
  --font-mono: var(--font-mono);
  --color-bg-canvas: var(--color-bg-canvas);
  --color-bg-surface: var(--color-bg-surface);
  --color-bg-elevated: var(--color-bg-elevated);
  --color-accent-primary: var(--color-accent-primary);
  --color-accent-hover: var(--color-accent-hover);
  --color-fg-primary: var(--color-fg-primary);
  --color-fg-muted: var(--color-fg-muted);
  --color-border-subtle: var(--color-border-subtle);
}
`;
}

/**
 * Generate Tailwind CSS v3 tailwind.config.ts configuration.
 */
function generateTailwindV3Config(tokens: DesignTokens): string {

  return `// Auto-generated by rea-steal-ui — Tailwind CSS v3 Configuration
import type { Config } from "tailwindcss";

export default {
  content: ["./src/**/*.{ts,tsx}"],
  darkMode: "class",
  theme: {
    extend: {
      colors: {
        bg: {
          canvas: "var(--color-bg-canvas)",
          surface: "var(--color-bg-surface)",
          elevated: "var(--color-bg-elevated)",
          overlay: "var(--color-bg-overlay)",
        },
        fg: {
          primary: "var(--color-fg-primary)",
          secondary: "var(--color-fg-secondary)",
          muted: "var(--color-fg-muted)",
          inverse: "var(--color-fg-inverse)",
        },
        border: {
          subtle: "var(--color-border-subtle)",
          strong: "var(--color-border-strong)",
          interactive: "var(--color-border-interactive)",
        },
        accent: {
          primary: "var(--color-accent-primary)",
          hover: "var(--color-accent-hover)",
          focus: "var(--color-accent-focus)",
        },
      },
      borderRadius: {
${Object.entries(tokens.radii)
  .map(([key, val]) => `        "${key}": "${val}",`)
  .join("\n")}
      },
      boxShadow: {
${Object.entries(tokens.shadows)
  .map(([key, val]) => `        "${key}": "${val}",`)
  .join("\n")}
      },
    },
  },
  plugins: [],
} satisfies Config;
`;
}

